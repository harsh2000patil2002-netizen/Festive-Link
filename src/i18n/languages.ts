/**
 * Centralized translation system for FestiveLink invitations.
 * Supports 22 Indian languages + English (default).
 *
 * Each language has:
 *  - code: ISO 639-1 / commonly used code
 *  - name: English name
 *  - native: native script name
 *  - dir: text direction ('ltr' or 'rtl')
 *  - fontStack: CSS font-family fallback chain for that script
 *  - numerals: native digits (null = use Western digits)
 *  - months: localized month names
 *  - t: the invitation string table
 */

export type LangDir = 'ltr' | 'rtl';
export type LangCode =
  | 'en' | 'hi' | 'mr' | 'gu' | 'bn' | 'ta' | 'te' | 'kn' | 'ml'
  | 'pa' | 'or' | 'as' | 'ne' | 'sa' | 'ur' | 'sd' | 'kok'
  | 'mai' | 'doi' | 'brx' | 'sat' | 'ks' | 'mni';

