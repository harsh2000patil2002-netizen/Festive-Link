export const LANG_MAP: Record<LangCode, LanguageInfo> = Object.fromEntries(
  LANGUAGES.map((l) => [l.code, l]),
) as Record<LangCode, LanguageInfo>;

export function getLang(code: LangCode): LanguageInfo {
  return LANG_MAP[code] ?? LANG_MAP.en;
}

/** Convert a number to native numerals if the language defines them */
export function toNativeDigits(n: number | string, code: LangCode): string {
  const lang = getLang(code);
  if (!lang.numerals) return String(n);
  return String(n)
    .split('')
    .map((ch) => (/[0-9]/.test(ch) ? lang.numerals![parseInt(ch, 10)] : ch))
    .join('');
}

/** Format a date (YYYY-MM-DD) into a localized date string */
export function formatDate(dateStr: string, code: LangCode): string {
  const lang = getLang(code);
  const d = new Date(dateStr + 'T00:00:00');
  if (isNaN(d.getTime())) return dateStr;
  const day = d.getDate();
  const month = lang.months[d.getMonth()];
  const year = d.getFullYear();
  const dayStr = lang.numerals ? toNativeDigits(day, code) : String(day);
  const yearStr = lang.numerals ? toNativeDigits(year, code) : String(year);
  return `${dayStr} ${month} ${yearStr}`;
}

/** Format the sample date (Aug 27, 2026) for a given language */
export function formatSampleDate(code: LangCode): string {
  return formatDate('2026-08-27', code);
}
